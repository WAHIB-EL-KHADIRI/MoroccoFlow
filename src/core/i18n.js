let locale = localStorage.getItem("mf-locale") || "fr";

export const t = (key) => messages[locale]?.[key] ?? messages.fr[key] ?? key;
export const getLocale = () => locale;

export function setLocale(nextLocale) {
  locale = nextLocale === "ar" ? "ar" : "fr";
  localStorage.setItem("mf-locale", locale);
  document.documentElement.lang = locale;
  document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
  window.dispatchEvent(new CustomEvent("mf:locale-change", { detail: { locale } }));
}

export function initLocale() {
  setLocale(locale);
}
